export function getTranslation(lang, path) {
  const keys = path.split('.');
  let current = translations[lang] || translations.id;
  for (const key of keys) {
    if (current && current[key] !== undefined) {
      current = current[key];
    } else {
      return path;
    }
  }
  return current;
}
